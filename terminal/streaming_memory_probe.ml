open! Core
open! Async
open Terminal_presentation
module S = Silver_protocol.Simulation

(* No source trace or list of pages: each requested page is generated by offset. *)
let byte_at offset = Char.of_int_exn (offset % 251)

let run size sha256 =
  assert (S.Limits.byte_page = Streaming_export.page_bytes);
  assert (S.Limits.artifact_bytes = Streaming_export.max_bytes);
  let artifact : S.Artifact.t =
    { id = "memory-trace"
    ; attempt_id = "memory-attempt"
    ; case_id = None
    ; label = "Synthetic binary trace"
    ; kind = "waveform"
    ; media_type = "application/octet-stream"
    ; size = Some size
    ; sha256 = Some sha256
    ; availability = Available
    }
  in
  let pages = ref 0 in
  let position = ref 0 in
  let fetch ~offset ~limit =
    assert (offset = !position && limit = S.Limits.byte_page);
    let length = Int.min limit (size - offset) in
    let bytes = String.init length ~f:(fun i -> byte_at (offset + i)) in
    position := offset + length;
    incr pages;
    return
      (Ok
         { S.Byte_page.attempt_id = artifact.attempt_id
         ; artifact_id = artifact.id
         ; sha256
         ; offset
         ; next_offset = !position
         ; total_size = size
         ; eof = !position = size
         ; bytes_hex = Cryptokit.transform_string (Cryptokit.Hexa.encode ()) bytes
         })
  in
  let%map result =
    Simulation_export.run ~artifact ~fetch ~current:(fun () -> true) ~viewer:None
      ~launch:(fun ~prog:_ ~args:_ -> failwith "Unexpected viewer launch")
  in
  let path = Or_error.ok_exn result in
  let directory = Filename.dirname path in
  let metadata = Filename.concat directory "metadata.sexp" in
  Exn.protect
    ~finally:(fun () ->
      Core_unix.unlink path;
      Core_unix.unlink metadata;
      Core_unix.rmdir directory)
    ~f:(fun () ->
      assert (!position = size);
      assert (!pages = Int.max 1 ((size + S.Limits.byte_page - 1) / S.Limits.byte_page));
      assert (String.is_suffix directory ~suffix:"-verified");
      let registered = S.Artifact.t_of_sexp (Sexp.load_sexp metadata) in
      assert (S.Artifact.equal artifact registered);
      (* Independently inspect the published file, still using one bounded buffer. *)
      let count = ref 0 in
      let hash = Cryptokit.Hash.sha256 () in
      let buffer = Bytes.create S.Limits.byte_page in
      In_channel.with_file path ~binary:true ~f:(fun input ->
        let rec loop () =
          let n = In_channel.input input ~buf:buffer ~pos:0 ~len:(Bytes.length buffer) in
          if n > 0
          then (
            for i = 0 to n - 1 do
              assert (Char.equal (Bytes.get buffer i) (byte_at (!count + i)))
            done;
            count := !count + n;
            hash#add_substring buffer 0 n;
            loop ())
        in
        loop ());
      let actual_sha256 = Streaming_export.digest hash in
      assert (!count = size && String.equal actual_sha256 sha256);
      Out_channel.output_string Out_channel.stdout
        (sprintf "{\"bytes\":%d,\"pages\":%d,\"sha256\":\"%s\",\"verified\":true}\n"
           !count !pages actual_sha256);
      Out_channel.flush Out_channel.stdout)
;;

let () =
  match Sys.get_argv () with
  | [| _; size; sha256 |] ->
    Thread_safe.block_on_async_exn (fun () -> run (Int.of_string size) sha256)
  | _ -> failwith "Usage: streaming_memory_probe.exe SIZE EXPECTED_SHA256"
;;
